// CLASE CORE: CustomAlert (Z-INDEX EXTREMO PARA SOBREPONERSE A MODALES)
// --------------------------------------------------------------
class CustomAlert {
    // Contenedor estático único
    static #container = null;
    static #defaultDuration = 5500;  // ms antes de auto-cerrar

    /**
     * Obtiene o crea el contenedor raíz con el máximo z-index posible
     * @returns {HTMLElement}
     */
    static #getContainer() {
        if (!this.#container || !document.body.contains(this.#container)) {
            let container = document.getElementById('customAlertRoot');
            if (!container) {
                container = document.createElement('div');
                container.id = 'customAlertRoot';
                container.className = 'custom-alert-global-container';
                // Reforzar z-index inline por si algún CSS externo lo sobrescribe
                container.style.zIndex = '2147483647';
                document.body.appendChild(container);
            } else {
                // Asegurar el z-index incluso si ya existe en el DOM
                container.style.zIndex = '2147483647';
            }
            this.#container = container;
        }
        return this.#container;
    }

    /**
     * Muestra una alerta personalizada siempre visible por encima de modales
     * @param {string} message - Texto del mensaje
     * @param {string} type - 'error', 'success', 'warning'
     * @param {number} duration - Duración en ms (0 = sin auto cierre)
     * @returns {HTMLElement}
     */
    static show(message, type, duration = this.#defaultDuration) {
        if (!message || typeof message !== 'string') {
            message = 'Notificación';
        }

        let normalizedType = String(type).toLowerCase();
        let alertTypeClass = '';

        if (normalizedType === 'error' || normalizedType === 'danger') {
            alertTypeClass = 'alert-type-error';
        } else if (normalizedType === 'success' || normalizedType === 'exito' || normalizedType === 'ok') {
            alertTypeClass = 'alert-type-success';
        } else if (normalizedType === 'warning' || normalizedType === 'advertencia' || normalizedType === 'warn') {
            alertTypeClass = 'alert-type-warning';
        } else {
            alertTypeClass = 'alert-type-warning'; // fallback seguro
        }

        // Crear elemento alerta
        const alertElement = document.createElement('div');
        alertElement.className = `custom-alert-item ${alertTypeClass}`;
        // Forzar posición relativa o lo que sea, pero el contenedor ya es fixed con z-index máximo

        const messageSpan = document.createElement('span');
        messageSpan.className = 'alert-message-text';
        messageSpan.textContent = message;

        const closeButton = document.createElement('button');
        closeButton.className = 'alert-close-button';
        closeButton.innerHTML = '✕';
        closeButton.setAttribute('aria-label', 'Cerrar alerta');

        const closeAlertWithAnimation = () => {
            if (!alertElement || !alertElement.parentNode) return;
            alertElement.classList.add('exit-animation');
            setTimeout(() => {
                if (alertElement && alertElement.parentNode) {
                    alertElement.parentNode.removeChild(alertElement);
                }
            }, 200);
            if (alertElement._timeoutId) {
                clearTimeout(alertElement._timeoutId);
                delete alertElement._timeoutId;
            }
        };

        closeButton.addEventListener('click', closeAlertWithAnimation);
        alertElement.appendChild(messageSpan);
        alertElement.appendChild(closeButton);

        const container = CustomAlert.#getContainer();
        container.appendChild(alertElement);

        if (duration && duration > 0) {
            const timeoutId = setTimeout(() => {
                if (alertElement && alertElement.parentNode) {
                    closeAlertWithAnimation();
                }
            }, duration);
            alertElement._timeoutId = timeoutId;
        }

        return alertElement;
    }

    static error(message, duration = this.#defaultDuration) {
        return this.show(message, 'error', duration);
    }

    static success(message, duration = this.#defaultDuration) {
        return this.show(message, 'success', duration);
    }

    static warning(message, duration = this.#defaultDuration) {
        return this.show(message, 'warning', duration);
    }

    // Métodos de instancia (alternativa)
    constructor(options = {}) {
        this.defaultDuration = options.duration || CustomAlert.#defaultDuration;
    }

    show(message, type, duration = this.defaultDuration) {
        return CustomAlert.show(message, type, duration);
    }

    error(message, duration = this.defaultDuration) {
        return CustomAlert.error(message, duration);
    }

    success(message, duration = this.defaultDuration) {
        return CustomAlert.success(message, duration);
    }

    warning(message, duration = this.defaultDuration) {
        return CustomAlert.warning(message, duration);
    }
}

// Exponer globalmente
window.CustomAlert = CustomAlert;